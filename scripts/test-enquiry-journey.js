'use strict';
const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const {join}=require('node:path');
const {JSDOM}=require('jsdom');
const html=readFileSync(join(__dirname,'../public/journey/index.html'),'utf8');
const js=readFileSync(join(__dirname,'../public/journey/app.js'),'utf8');

for(const response of ['interested','changes','declined']){
  const dom=new JSDOM(html,{url:'https://example.invalid/journey-demo',runScripts:'outside-only'});
  const w=dom.window,d=w.document;
  let externalEffects=0;
  const blocked=()=>{externalEffects++;throw new Error('The fictional journey must stay in memory.');};
  w.fetch=blocked;w.XMLHttpRequest=blocked;w.WebSocket=blocked;w.EventSource=blocked;
  w.Storage.prototype.setItem=blocked;
  w.eval(js);
  const act=()=>d.querySelector('#actions button').click();
  assert.equal(d.getElementById('journey-enquiry').getAttribute('aria-pressed'),'true');
  assert.match(d.getElementById('content').textContent,/Nettsideskjema/);
  act();act();
  const draft=d.getElementById('reply-draft');
  draft.value='   ';act();
  assert.equal(draft.getAttribute('aria-invalid'),'true');
  assert.match(d.getElementById('feedback').textContent,/Skriv et svar/);
  assert.equal(d.querySelectorAll('#steps button:disabled').length,3);
  const approved='Hei Nora!\nKan du fortelle mer om bilen? <img src=x onerror=alert(1)>';
  draft.value=approved;draft.dispatchEvent(new w.Event('input'));act();
  assert.match(d.getElementById('summary').textContent,/Avventer kundesvar/);
  assert.equal(d.querySelectorAll('#content img').length,0);
  assert.ok(d.getElementById('content').textContent.includes(approved));
  assert.equal(d.querySelectorAll('#steps button:disabled').length,3,'approval alone does not skip the clarification');
  act();
  assert.match(d.getElementById('content').textContent,/Volvo V60/);
  assert.match(d.getElementById('summary').textContent,/Trenger oppfølging/);
  assert.match(d.getElementById('alert-title').textContent,/Nytt svar i henvendelsen/);
  assert.match(d.getElementById('alert-copy').textContent,/arbeidsoversikten/);assert.doesNotMatch(d.getElementById('alert-copy').textContent,/e-post/);
  assert.match(d.getElementById('summary').textContent,/Salgsverdi0 kr/);
  act();act();act();
  d.querySelector(`[value=${response}]`).checked=true;act();act();
  act();assert.match(d.getElementById('feedback').textContent,/Bekreft/);
  d.getElementById('verified').checked=true;
  if(response==='changes')d.querySelector('[value=followup]').checked=true;
  act();
  assert.match(d.getElementById('summary').textContent,response==='interested'?/8 900 kr · manuelt registrert/:response==='changes'?/avtalt tidspunkt/:/Avsluttet/);
  assert.equal(d.querySelectorAll('#timeline li').length,6);
  assert.ok(d.querySelector('#actions a[href="/workspace-demo"]'));
  d.querySelectorAll('#steps button')[1].click();
  assert.ok(d.getElementById('content').textContent.includes(approved));
  assert.equal(d.querySelectorAll('#timeline li').length,6,'revisiting preserves the same conversation');
  d.getElementById('reset').click();
  assert.match(d.getElementById('summary').textContent,/Ikke registrert/);
  assert.equal(d.querySelectorAll('#steps button:disabled').length,4);
  d.getElementById('journey-booking').click();
  act();act();
  assert.ok(d.querySelector('[value="Onsdag kl. 10:30"]'),'original booking journey remains selectable');
  d.getElementById('journey-enquiry').click();
  assert.match(d.getElementById('summary').textContent,/Ikke registrert/);
  assert.equal(w.localStorage.length,0);assert.equal(w.sessionStorage.length,0);assert.equal(externalEffects,0);
  w.close();
  console.log('ok - enquiry reply approval, same-case clarification, guarded outcome and isolated demo: '+response);
}
